function allergenSet(
  entries: Partial<
    Record<
      Restaurant["allergens"][number]["allergen"],
      {
        present: boolean | null;
        source: Restaurant["allergens"][number]["source"];
        notes?: string;
      }
    >
  >,
): Restaurant["allergens"] {
  const all = [
    "celery",
    "cereals_gluten",
    "crustaceans",
    "eggs",
    "fish",
    "lupin",
    "milk",
    "molluscs",
    "mustard",
    "nuts",
    "peanuts",
    "sesame",
    "soybeans",
    "sulphites",
  ] as const;

  return all.map((allergen) => {
    const e = entries[allergen];
    if (!e) {
      return { allergen, present: null, source: "unavailable" as const };
    }
    return { allergen, ...e };
  });
}

